"""Keep product discovery distinct from implementation planning."""
import re


def product_discovery(goal):
    text = goal.lower()
    product = re.search(r'app|应用|软件|产品|工具', text)
    discovery = re.search(r'做什么|做一个什么|开发什么|开发一款|开发一个|爆火|赚钱|卖点|产品创意|产品方向|选题|市场机会|app idea|product idea', text)
    return bool(product and discovery)


