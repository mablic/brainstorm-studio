const KINDS = ['personas', 'feedback', 'clarify', 'research', 'discussion', 'summary', 'custom'];
let lang = readLang();

function readLang() {
  try {
    const saved = globalThis.localStorage?.getItem('brainstorm-lang');
    if (saved === 'en' || saved === 'zh') return saved;
  } catch { /* private mode or tests */ }
  if (typeof window !== 'undefined') {
    const browser = window.navigator?.language || '';
    if (browser && !browser.toLowerCase().startsWith('zh')) return 'en';
  }
  return 'zh';
}

const listeners = new Set();

export function getLang() { return lang; }

export function t(key, vars) {
  let text = STRINGS[lang][key] ?? STRINGS.zh[key] ?? key;
  if (vars) for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value));
  return text;
}

export function setLang(next) {
  if (next !== 'zh' && next !== 'en') return getLang();
  lang = next;
  try { globalThis.localStorage?.setItem('brainstorm-lang', next); } catch { /* ignore */ }
  applyDocumentLanguage();
  listeners.forEach(fn => fn(lang));
  return lang;
}

export function subscribe(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

export function applyDocumentLanguage() {
  if (typeof document === 'undefined') return;
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
  document.title = t('app.title');
}

export function stepCopy(code) {
  const pack = STRINGS[code] || STRINGS.zh;
  return Object.fromEntries(KINDS.map(kind => [kind, {
    label: pack[`step.${kind}.label`],
    description: pack[`step.${kind}.description`],
    rules: pack[`step.${kind}.rules`],
  }]));
}

export function localizeSteps(steps, code) {
  const zh = stepCopy('zh');
  const en = stepCopy('en');
  const target = code === 'en' ? en : zh;
  let changed = false;
  const next = steps.map(step => {
    const options = [zh[step.kind], en[step.kind]].filter(Boolean);
    const dest = target[step.kind];
    if (!dest) return step;
    const title = options.some(item => item.label === step.title) ? dest.label : step.title;
    const instructions = options.some(item => item.rules === step.instructions) ? dest.rules : step.instructions;
    if (title === step.title && instructions === step.instructions) return step;
    changed = true;
    return { ...step, title, instructions };
  });
  return changed ? next : steps;
}

